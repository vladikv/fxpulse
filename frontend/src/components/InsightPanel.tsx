import { useEffect, useRef, useState } from 'react'
import { ApiRequestError, fetchInsight } from '../api/client'
import type { Insight } from '../api/types'
import { formatDate } from '../utils/format'
import type { Range } from '../utils/ranges'
import { CurrencyFlag } from './CurrencyFlag'

interface Props {
  code: string
  /** null while the picked range is invalid: the button is disabled then. */
  range: Range | null
}

/** What happened to the last request, remembered for the code + range it was made for. */
type Outcome =
  | { key: string; status: 'loading' }
  | { key: string; status: 'done'; insight: Insight }
  | { key: string; status: 'failed'; error: unknown }

const dateTimeFormat = new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium', timeStyle: 'short' })

/**
 * AI trend summary for the dashboard's currency and range.
 *
 * Generated only when the user clicks: every fresh insight is a Gemini call on a free-tier quota, so
 * it must not fire on each range change. The backend caches insights per (currency, from, to), and the
 * response says whether the text was cached.
 *
 * The outcome is stored with the key it belongs to; after the user changes the currency or range the
 * old insight no longer matches and is simply not shown (no effect needed to reset it).
 */
export function InsightPanel({ code, range }: Props) {
  const [outcome, setOutcome] = useState<Outcome | null>(null)
  const requestRef = useRef<AbortController | null>(null)

  useEffect(() => () => requestRef.current?.abort(), [])

  const key = range ? `${code}|${range.from}|${range.to}` : null
  const current = outcome !== null && outcome.key === key ? outcome : null
  const loading = current?.status === 'loading'

  async function generate() {
    if (!range || key === null) {
      return
    }
    requestRef.current?.abort()
    const controller = new AbortController()
    requestRef.current = controller
    setOutcome({ key, status: 'loading' })
    try {
      const insight = await fetchInsight(code, range, controller.signal)
      setOutcome({ key, status: 'done', insight })
    } catch (error) {
      if (!controller.signal.aborted) {
        setOutcome({ key, status: 'failed', error })
      }
    }
  }

  return (
    <section className="panel">
      <div className="panel-header">
        <div>
          <h2 className="panel-title">
            <span className="ai-mark" aria-hidden="true">
              ✦
            </span>{' '}
            AI trend summary
          </h2>
          {range && (
            <p className="panel-subtitle">
              <CurrencyFlag code={code} /> {code} / PLN · {formatDate(range.from)} – {formatDate(range.to)}
            </p>
          )}
        </div>
        <button type="button" className="primary" onClick={generate} disabled={!range || loading}>
          {loading ? 'Generating…' : 'Generate AI insight'}
        </button>
      </div>

      {!current && (
        <p className="muted">
          {range
            ? 'Click the button for a short plain-English summary of the period shown in the chart.'
            : 'Pick a valid date range first.'}
        </p>
      )}
      {loading && <p className="muted">Asking the AI model, this can take a few seconds…</p>}
      {current?.status === 'failed' && <InsightError error={current.error} />}
      {current?.status === 'done' && <InsightText insight={current.insight} />}

      <p className="muted small disclaimer">
        Generated by AI from NBP statistics. Informational only, not financial advice.
      </p>
    </section>
  )
}

/**
 * The model answers with one dense paragraph (3-4 sentences, ~7 numbers). To make it easy to scan:
 * the first sentence (overall direction) becomes the lead, the others get their own lines, and the
 * figures are highlighted. Everything is rendered as React text, never as HTML, so model output can't
 * inject markup.
 */
function InsightText({ insight }: { insight: Insight }) {
  const [lead, ...rest] = splitSentences(insight.content)

  return (
    <article className="insight" aria-live="polite">
      <p className="insight-lead">{highlightFigures(lead ?? '')}</p>
      {rest.map((sentence, index) => (
        <p key={index} className="insight-sentence">
          {highlightFigures(sentence)}
        </p>
      ))}
      <ul className="insight-meta" aria-label="About this summary">
        <li>
          <span className={insight.cached ? 'badge' : 'badge badge-new'}>{insight.cached ? 'Cached' : 'New'}</span>
        </li>
        <li>{insight.model}</li>
        <li>generated {dateTimeFormat.format(new Date(insight.createdAt))}</li>
      </ul>
    </article>
  )
}

/**
 * Splits on ". " followed by a capital letter, so decimals ("4.3925") and lower-case abbreviations
 * stay intact. Line breaks from the model also start a new part.
 */
function splitSentences(text: string): string[] {
  return text
    .split(/\n+/)
    .flatMap((line) => line.split(/(?<=[.!?])\s+(?=[A-Z])/))
    .map((part) => part.trim())
    .filter((part) => part !== '')
}

/** Rates in PLN and percentages, e.g. "4.3925 PLN", "0.31 percent", "-1.2%". */
const FIGURE = /([+-]?\d+(?:[.,]\d+)*\s?(?:PLN|percent|%))/

/** split() with a capture group keeps the matches at the odd indexes; those are wrapped in <strong>. */
function highlightFigures(sentence: string) {
  return sentence.split(FIGURE).map((part, index) =>
    index % 2 === 1 ? (
      <strong key={index} className="figure">
        {part}
      </strong>
    ) : (
      part
    ),
  )
}

/** A heading by HTTP status; the backend's ApiError message (already user-friendly) gives the details. */
function InsightError({ error }: { error: unknown }) {
  const message = error instanceof Error ? error.message : String(error)
  const status = error instanceof ApiRequestError ? error.status : undefined

  let title = 'Could not generate the insight'
  if (status === 429) {
    title = 'AI quota reached'
  } else if (status === 503) {
    title = 'AI is unavailable right now'
  } else if (status === 404) {
    title = 'No data for this range'
  }

  return (
    <div className="error" role="alert">
      <strong>{title}.</strong> {message}
    </div>
  )
}
